export function generateSvg(opts: GenerateOptions): string {
  const size = clampInt(opts.size ?? 128, 16, 512);
  const grid = GRID[opts.style];

  const hash = fnv1a(opts.seed);
  const palette = paletteFor(opts.style, hash, opts.palette);
  const bg = opts.background ?? palette.background;

  let inner = "";
  switch (opts.style) {
    case "identicon":
      inner = buildIdenticon(hash, palette);
      break;
    case "pixel":
      inner = buildPixel(hash, palette);
      break;
    case "abstract":
      inner = buildAbstract(hash, palette);
      break;
    case "anime":
      inner = buildAnime(hash, palette);
      break;
    case "xiuxian":
      inner = buildXiuxian(hash, palette);
      break;
    case "pixel-detail":
      inner = buildPixelDetail(hash, palette);
      break;
  }

  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${grid.cols} ${grid.rows}"`,
    ` width="${size}" height="${size}" shape-rendering="crispEdges"`,
    ` role="img" aria-label="Pixel avatar for ${escapeXml(opts.seed)}">`,
    `<rect width="${grid.cols}" height="${grid.rows}" fill="${bg}"/>`,
    inner,
    `</svg>`,
  ].join("");
}

function clampInt(n: number, lo: number, hi: number): number {
  if (!Number.isFinite(n)) return lo;
  return Math.min(hi, Math.max(lo, Math.trunc(n)));
}

function escapeXml(s: string): string {
  return s
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}
