/** Derive a coherent 1-3 color palette from a hash. */
function paletteFor(style: Style, hash: number, override?: string[]): Palette {
  if (override && override.length > 0) {
    return {
      background: override[0] ?? "#ffffff",
      foreground: override[1] ?? override[0] ?? "#000000",
      extras: override.slice(2),
    };
  }
  const hue = hash % 360;
  if (style === "identicon") {
    return {
      background: hslToHex(hue, 0.25, 0.92),
      foreground: hslToHex(hue, 0.7, 0.45),
      extras: [],
    };
  }
  if (style === "anime") {
    return {
      background: hslToHex(hue, 0.3, 0.93),
      foreground:
        ANIME_HAIR_COLORS[mix(hash, "hair") % ANIME_HAIR_COLORS.length] ??
        ANIME_HAIR_COLORS[0]!,
      extras: [
        ANIME_EYE_COLORS[mix(hash, "eye") % ANIME_EYE_COLORS.length] ??
          ANIME_EYE_COLORS[0]!,
        "#b3415c",
      ],
    };
  }
  if (style === "xiuxian") {
    return {
      background: hslToHex(hue, 0.25, 0.95),
      foreground:
        XIUXIAN_HAIR_COLORS[mix(hash, "hair") % XIUXIAN_HAIR_COLORS.length] ??
        XIUXIAN_HAIR_COLORS[0]!,
      extras: [
        XIUXIAN_EYE_COLORS[mix(hash, "eye") % XIUXIAN_EYE_COLORS.length] ??
          XIUXIAN_EYE_COLORS[0]!,
        "#7a3a2a",
      ],
    };
  }
  // pixel + abstract + pixel-detail: hue + 2 analogous accents.
  return {
    background: hslToHex(hue, 0.2, 0.94),
    foreground: hslToHex(hue, 0.6, 0.5),
    extras: [
      hslToHex((hue + 30) % 360, 0.55, 0.55),
      hslToHex((hue + 330) % 360, 0.55, 0.55),
    ],
  };
}

