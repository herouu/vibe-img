const PIXEL_COLORS: Record<0 | 1 | 2 | 3 | 4, keyof Palette | null> = {
  0: null,
  1: "foreground",
  2: "extras",
  3: "extras",
  4: "background",
};

function buildPixel(hash: number, palette: Palette): string {
  const variant = PIXEL_VARIANTS[hash % PIXEL_VARIANTS.length] ?? PIXEL_VARIANTS[0]!;
  const rects: string[] = [];
  for (let row = 0; row < 8; row++) {
    for (let col = 0; col < 8; col++) {
      const slot = variant.rows[row]?.[col] ?? 0;
      if (slot === 0) continue;
      const key = PIXEL_COLORS[slot];
      if (!key) continue;
      const fill =
        key === "extras"
          ? slot === 2
            ? (palette.extras[0] ?? palette.foreground)
            : (palette.extras[1] ?? palette.foreground)
          : key === "background"
            ? palette.background
            : palette[key];
      rects.push(`<rect x="${col}" y="${row}" width="1" height="1" fill="${fill}"/>`);
    }
  }
  return rects.join("");
}

