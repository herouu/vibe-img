function buildXiuxian(hash: number, palette: Palette): string {
  const variant =
    XIUXIAN_VARIANTS[hash % XIUXIAN_VARIANTS.length] ?? XIUXIAN_VARIANTS[0]!;
  const skin =
    ANIME_SKIN_TONES[mix(hash, "skin") % ANIME_SKIN_TONES.length] ??
    ANIME_SKIN_TONES[0]!;
  const robe =
    XIUXIAN_ROBE_COLORS[mix(hash, "robe") % XIUXIAN_ROBE_COLORS.length] ??
    XIUXIAN_ROBE_COLORS[0]!;
  const fills: readonly (string | null)[] = [
    null,
    palette.foreground,
    skin,
    palette.extras[0] ?? "#3b6fd4",
    "#ffffff",
    palette.extras[1] ?? "#7a3a2a",
    "#e89aa3",
    robe,
    XIUXIAN_CROWN_COLOR,
    XIUXIAN_SWORD_COLOR,
    "#9a9a9a",
    "#c84040",
    "#8b6f47",
    "#e8b04b",
    "#3a2418",
  ];
  const rects: string[] = [];
  for (let row = 0; row < 12; row++) {
    for (let col = 0; col < 12; col++) {
      const fill = fills[variant.rows[row]?.[col] ?? 0];
      if (!fill) continue;
      rects.push(`<rect x="${col}" y="${row}" width="1" height="1" fill="${fill}"/>`);
    }
  }
  return rects.join("");
}

function buildAbstract(hash: number, palette: Palette): string {
  const streams = [hash, mix(hash, "a"), mix(hash, "b"), mix(hash, "c")];
  const rects: string[] = [];
  for (let i = 0; i < 64; i++) {
    const word = streams[i >> 5]!;
    const shift = (i & 31) * 2;
    const v = (word >>> shift) & 0b11;
    if (v === 0) continue;
    const colors = [palette.foreground, ...palette.extras];
    const fill = colors[v - 1] ?? palette.foreground;
    const col = i & 7;
    const row = i >> 3;
    rects.push(`<rect x="${col}" y="${row}" width="1" height="1" fill="${fill}"/>`);
  }
  return rects.join("");
}

