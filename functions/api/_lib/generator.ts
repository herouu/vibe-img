/* Draw a filled ellipse as horizontal spans (pixel-perfect). */
function fillEllipse(
  canvas: PixelCanvas,
  cx: number,
  cy: number,
  rx: number,
  ry: number,
  color: string,
): void {
  for (let y = cy - ry; y <= cy + ry; y++) {
    const row = Math.round(y);
    if (row < 0 || row >= 64) continue;
    const dy = (y - cy) / ry;
    const dx = Math.sqrt(Math.max(0, 1 - dy * dy));
    const x0 = Math.round(cx - dx * rx);
    const x1 = Math.round(cx + dx * rx);
    for (let x = x0; x <= x1; x++) {
      if (x >= 0 && x < 64) canvas.set(x, row, color);
    }
  }
}

const PLANT_TYPES = [
  "flower",
  "cactus",
  "succulent",
  "mushroom",
  "tree",
  "bonsai",
  "tulip",
  "aloe",
  "bamboo",
  "sunflower",
] as const;
type PlantType = (typeof PLANT_TYPES)[number];

interface PlantLayout {
  readonly typeIndex: number;
  readonly variant: number;
  readonly potShape: number;
  readonly cx: number;
  readonly potTopY: number;
  readonly potBottomY: number;
  readonly potTopW: number;
  readonly potBottomW: number;
  readonly stemTopY: number;
  readonly bloomCx: number;
  readonly bloomCy: number;
  readonly bloomR: number;
}

function buildPlantLayout(hash: number): PlantLayout {
  const typeIndex = mix(hash, "p-type") % PLANT_TYPES.length;
  const variant = mix(hash, "p-var") % 4;
  const potShape = mix(hash, "p-pots") % 4;
  const cx = 32;
  const potBottomY = 62;
  // Default (classic) dimensions; overridden per pot shape below
  let potTopY = 44;
  let potTopW = 24 + variant;
  let potBottomW = 20 + variant;
  if (potShape === 1) {
    // Tall cylindrical
    potTopY = 38;
    potTopW = 18 + variant;
    potBottomW = 18 + variant;
  } else if (potShape === 2) {
    // Shallow wide bowl
    potTopY = 48;
    potTopW = 28 + variant;
    potBottomW = 24 + variant;
  } else if (potShape === 3) {
    // Square planter
    potTopY = 46;
    potTopW = 24 + variant;
    potBottomW = 24 + variant;
  }

  const t: PlantType = PLANT_TYPES[typeIndex] ?? "flower";
  let stemTopY = 23;
  let bloomCy = 12;
  let bloomR = 5;
  if (t === "cactus") { stemTopY = 12; bloomCy = 10; bloomR = 3; }
  else if (t === "succulent") { stemTopY = 43; bloomCy = 30; bloomR = 11; }
  else if (t === "mushroom") { stemTopY = 24; bloomCy = 15; bloomR = 12; }
  else if (t === "tree") { stemTopY = 25; bloomCy = 14; bloomR = 15; }
  else if (t === "bonsai") { stemTopY = 32; bloomCy = 20; bloomR = 8; }
  else if (t === "tulip") { stemTopY = 22; bloomCy = 16; bloomR = 4; }
  else if (t === "aloe") { stemTopY = 43; bloomCy = 32; bloomR = 12; }
  else if (t === "bamboo") { stemTopY = 6; bloomCy = 6; bloomR = 2; }
  else if (t === "sunflower") { stemTopY = 22; bloomCy = 12; bloomR = 6; }

  return {
    typeIndex,
    variant,
    potShape,
    cx,
    potTopY,
    potBottomY,
    potTopW,
    potBottomW,
    stemTopY,
    bloomCx: cx,
    bloomCy,
    bloomR,
  };
}

/* Draw a tapered leaf pointing in `dir` (-1 left, +1 right). */
function drawLeaf(
  canvas: PixelCanvas,
  cx: number,
  cy: number,
  dir: -1 | 1,
  len: number,
  color: string,
  shadow: string,
  highlight: string,
): void {
  for (let t = 0; t < len; t++) {
    const progress = t / Math.max(1, len - 1);
    const halfW = Math.max(1, Math.round(2 * Math.sin(progress * Math.PI)));
    const x = cx + dir * t;
    const y = cy - Math.round(progress * 2);
    if (x < 0 || x >= 64 || y < 0 || y >= 64) continue;
    for (let dx = -halfW; dx <= halfW; dx++) {
      const px = x + dx;
      if (px < 0 || px >= 64) continue;
      const isEdge = Math.abs(dx) >= halfW - 1;
      const isTop = dx > halfW / 3;
      let c = color;
      if (isEdge) c = shadow;
      else if (isTop) c = highlight;
      canvas.set(px, y, c);
    }
  }
}

function drawPot(
  c: PixelCanvas,
  p: PlantPalette,
  l: PlantLayout,
): void {
  switch (l.potShape) {
    case 1:
      drawPotTall(c, p, l);
      break;
    case 2:
      drawPotShallow(c, p, l);
      break;
    case 3:
      drawPotSquare(c, p, l);
      break;
    default:
      drawPotClassic(c, p, l);
      break;
  }
}

function drawSoil(
  c: PixelCanvas,
  p: PlantPalette,
  cx: number,
  topY: number,
  topHW: number,
): void {
  for (let dx = -topHW + 1; dx <= topHW - 1; dx++) {
    const x = cx + dx;
    if (x < 0 || x >= 64) continue;
    c.set(x, topY, p.soil);
    if (topY - 1 >= 0) c.set(x, topY - 1, p.soil);
  }
}

function drawPotClassic(c: PixelCanvas, p: PlantPalette, l: PlantLayout): void {
  const cx = l.cx;
  const topY = l.potTopY;
  const botY = l.potBottomY;
  const topHW = Math.round(l.potTopW / 2);
  const botHW = Math.round(l.potBottomW / 2);
  for (let y = topY; y <= botY; y++) {
    if (y < 0 || y >= 64) continue;
    const t = (y - topY) / Math.max(1, botY - topY);
    const hw = Math.round(topHW + (botHW - topHW) * t);
    const isRim = t < 0.18;
    for (let dx = -hw; dx <= hw; dx++) {
      const x = cx + dx;
      if (x < 0 || x >= 64) continue;
      let color: string;
      if (isRim) {
        color = Math.abs(dx) >= hw - 1 ? p.potShadow : p.potRim;
      } else {
        if (Math.abs(dx) >= hw - 1) color = p.potShadow;
        else if (dx === 1) color = p.potHighlight;
        else color = p.pot;
      }
      c.set(x, y, color);
    }
  }
  drawSoil(c, p, cx, topY, topHW);
}

function drawPotTall(c: PixelCanvas, p: PlantPalette, l: PlantLayout): void {
  const cx = l.cx;
  const topY = l.potTopY;
  const botY = l.potBottomY;
  const hw = Math.round(l.potTopW / 2);
  const rimRows = 3;
  // Rim
  for (let y = topY; y <= topY + rimRows - 1 && y < 64; y++) {
    if (y < 0) continue;
    for (let dx = -hw; dx <= hw; dx++) {
      const x = cx + dx;
      if (x < 0 || x >= 64) continue;
      const color = Math.abs(dx) >= hw - 1 ? p.potShadow : p.potRim;
      c.set(x, y, color);
    }
  }
  // Cylindrical body with slight bottom taper
  for (let y = topY + rimRows; y <= botY; y++) {
    if (y < 0 || y >= 64) continue;
    const t = (y - topY - rimRows) / Math.max(1, botY - topY - rimRows);
    const curHW = Math.max(2, Math.round(hw * (1 - t * 0.12)));
    for (let dx = -curHW; dx <= curHW; dx++) {
      const x = cx + dx;
      if (x < 0 || x >= 64) continue;
      let color: string;
      if (Math.abs(dx) >= curHW - 1) color = p.potShadow;
      else if (dx === 1) color = p.potHighlight;
      else color = p.pot;
      c.set(x, y, color);
    }
  }
  // Decorative ring
  for (let x = cx - hw + 2; x <= cx + hw - 2; x++) {
    if (x < 0 || x >= 64) continue;
    const y = topY + rimRows + 4;
    if (y >= 0 && y < 64) c.set(x, y, p.potShadow);
  }
  // Vertical seam (subtle)
  for (let y = topY + rimRows; y <= botY - 2; y++) {
    if (y < 0 || y >= 64) continue;
    if (cx - 1 >= 0) c.set(cx - 1, y, p.potShadow);
  }
  drawSoil(c, p, cx, topY, hw);
}

function drawPotShallow(c: PixelCanvas, p: PlantPalette, l: PlantLayout): void {
  const cx = l.cx;
  const topY = l.potTopY;
  const botY = l.potBottomY;
  const topHW = Math.round(l.potTopW / 2);
  const botHW = Math.round(l.potBottomW / 2);
  for (let y = topY; y <= botY; y++) {
    if (y < 0 || y >= 64) continue;
    const t = (y - topY) / Math.max(1, botY - topY);
    // Slight outward bulge in the middle (bowl curve)
    const bulge = 1 + Math.sin(t * Math.PI) * 0.12;
    const hw = Math.max(2, Math.round((topHW + (botHW - topHW) * t) * bulge));
    const isRim = t < 0.18;
    for (let dx = -hw; dx <= hw; dx++) {
      const x = cx + dx;
      if (x < 0 || x >= 64) continue;
      let color: string;
      if (isRim) {
        color = Math.abs(dx) >= hw - 1 ? p.potShadow : p.potRim;
      } else {
        if (Math.abs(dx) >= hw - 1) color = p.potShadow;
        else if (dx === 1) color = p.potHighlight;
        else color = p.pot;
      }
      c.set(x, y, color);
    }
  }
  // Foot ring (saucer hint) below the bowl
  for (let x = cx - topHW + 2; x <= cx + topHW - 2; x++) {
    if (x < 0 || x >= 64) continue;
    if (botY + 1 < 64) c.set(x, botY + 1, p.potShadow);
  }
  drawSoil(c, p, cx, topY, topHW);
}

function drawPotSquare(c: PixelCanvas, p: PlantPalette, l: PlantLayout): void {
  const cx = l.cx;
  const topY = l.potTopY;
  const botY = l.potBottomY;
  const hw = Math.round(l.potTopW / 2);
  for (let y = topY; y <= botY; y++) {
    if (y < 0 || y >= 64) continue;
    const isRim = y < topY + 2;
    for (let dx = -hw; dx <= hw; dx++) {
      const x = cx + dx;
      if (x < 0 || x >= 64) continue;
      let color: string;
      if (isRim) {
        color = Math.abs(dx) >= hw - 1 ? p.potShadow : p.potRim;
      } else {
        if (Math.abs(dx) >= hw) color = p.potShadow;
        else if (dx === 1) color = p.potHighlight;
        else color = p.pot;
      }
      c.set(x, y, color);
    }
  }
  // Side panel divider (suggests 3D)
  for (let y = topY + 2; y <= botY; y++) {
    if (y < 0 || y >= 64) continue;
    if (cx - hw + 1 >= 0) c.set(cx - hw + 1, y, p.potShadow);
  }
  // Feet (two small blocks)
  if (botY + 1 < 64) {
    if (cx - hw + 2 >= 0) c.set(cx - hw + 2, botY + 1, p.potShadow);
    if (cx + hw - 2 < 64) c.set(cx + hw - 2, botY + 1, p.potShadow);
  }
  drawSoil(c, p, cx, topY, hw);
}

function drawStemColumn(
  c: PixelCanvas,
  p: PlantPalette,
  cx: number,
  topY: number,
  bottomY: number,
  width: number,
): void {
  const hw = Math.floor(width / 2);
  for (let y = topY; y <= bottomY; y++) {
    if (y < 0 || y >= 64) continue;
    for (let dx = -hw; dx <= hw; dx++) {
      const x = cx + dx;
      if (x < 0 || x >= 64) continue;
      let color: string;
      if (dx === -hw) color = p.stemShadow;
      else if (dx === hw) color = p.stemHighlight;
      else color = p.stem;
      c.set(x, y, color);
    }
  }
}

