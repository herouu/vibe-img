/**
 * Deterministic pixel avatar generator.
 *
 * Pure functions only. No I/O, no Web APIs, no randomness — given the same
 * inputs (seed, style, cellSize) the output is byte-identical, which lets the
 * Pages Function return `Cache-Control: immutable` without coordination.
 *
 * All render as SVG so the same source scales to any pixel density without
 * re-rasterization.
 *
 *   identicon    - 5x5 symmetric tile pattern (GitHub-style, two-tone)
 *   pixel        - 8x8 chibi face with hashed template variation
 *   abstract     - 8x8 multi-color tile composition
 *   anime        - 12x12 cartoon portrait (30 variants: hair, eyes, mouth, accessories)
 *   xiuxian      - 12x12 Chinese cultivation portrait (30 variants: crowns, weapons, accessories, props)
 *   pixel-detail - 64x64 layered potted plant
 *     Plants: flower / cactus / succulent / mushroom / tree / bonsai / tulip / aloe / bamboo / sunflower
 *     Tree sub-types: round, pine, palm, weeping
 *     Pot shapes: classic, tall, shallow, square
 */

export type Style =
  | "identicon"
  | "pixel"
  | "abstract"
  | "anime"
  | "xiuxian"
  | "pixel-detail";

export interface GenerateOptions {
  seed: string;
  style: Style;
  /** Total width/height of the output SVG in pixels. Default 128. */
  size?: number;
  /** Background color override. Defaults to a light tint derived from seed. */
  background?: string;
  /** Foreground palette override. Defaults to a palette derived from seed. */
  palette?: string[];
}

