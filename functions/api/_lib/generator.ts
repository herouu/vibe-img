function buildAnime(hash: number, palette: Palette): string {
  const variant = ANIME_VARIANTS[hash % ANIME_VARIANTS.length] ?? ANIME_VARIANTS[0]!;
  const skin =
    ANIME_SKIN_TONES[mix(hash, "skin") % ANIME_SKIN_TONES.length] ??
    ANIME_SKIN_TONES[0]!;
  const fills: readonly (string | null)[] = [
    null,
    palette.foreground,
    skin,
    palette.extras[0] ?? "#3b6fd4",
    "#ffffff",
    palette.extras[1] ?? "#b3415c",
    "#f5a3b7",
    palette.extras[2] ?? "#5fa8d3",
  ];
  const rects: string[] = [];
  for (let row = 0; row < 12; row++) {
    for (let col = 0; col < 12; col++) {
      const fill = fills[variant.rows[row]?.[col] ?? 0];
      if (!fill) continue;
      rects.push(`<rect x="${col}" y="${row}" width="1" height="1" fill="${fill}"/>`);
    }
  }
  return rects.join("");
}

