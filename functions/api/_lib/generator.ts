/* Hash                                                                */
/* ------------------------------------------------------------------ */

/** FNV-1a 32-bit. Fast, good enough for visual variety; not cryptographic. */
function fnv1a(input: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

/** Mix a base hash with a salt to get independent bit streams. */
function mix(base: number, salt: string): number {
  return fnv1a(`${base.toString(16)}|${salt}`);
}

/** Deterministic pick from an array using hash + salt. */
function pick<T>(hash: number, salt: string, arr: readonly T[]): T {
  return arr[mix(hash, salt) % arr.length]!;
}

