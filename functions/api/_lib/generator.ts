function buildIdenticon(hash: number, palette: Palette): string {
  const cells: string[] = [];
  for (let row = 0; row < 5; row++) {
    for (let col = 0; col < 3; col++) {
      const bit = (hash >> (row * 3 + col)) & 1;
      if (bit) {
        const x = col;
        const xMirror = 4 - col;
        cells.push(`M${x},${row}h1v1h-1z`);
        if (xMirror !== col) cells.push(`M${xMirror},${row}h1v1h-1z`);
      }
    }
  }
  return `<path d="${cells.join("")}" fill="${palette.foreground}"/>`;
}

